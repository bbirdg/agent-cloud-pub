/**
 * The memory server's Wrangler config, generated from agent-cloud.json into <project>/.agent-cloud/ (git-ignored),
 * and Wrangler itself (a dependency of this package), run with that config.
 */
import { execFileSync, type ExecFileSyncOptions } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { packageRoot, type Settings } from "./project.ts";

export const buildDir = (project: string) => path.join(project, ".agent-cloud");
export const configPath = (project: string) => path.join(buildDir(project), "wrangler.jsonc");
export const assetsDir = (project: string) => path.join(buildDir(project), "assets");

const DEFAULT_COMPATIBILITY_DATE = "2026-11-25";

/** Writes the Worker config for these settings; returns its path. */
export function writeWranglerConfig(project: string, s: Settings): string {
  const dir = buildDir(project);
  mkdirSync(assetsDir(project), { recursive: true });
  const rel = (p: string) => path.relative(dir, p).split(path.sep).join("/");
  const config = {
    name: s.memory.worker,
    main: rel(path.join(packageRoot, "server", "src", "index.ts")),
    compatibility_date: s.memory.compatibilityDate ?? DEFAULT_COMPATIBILITY_DATE,
    compatibility_flags: ["nodejs_compat", "global_fetch_strictly_public"],
    // With a custom domain the workers.dev address is off; preview URLs are always off.
    workers_dev: !s.memory.domain,
    preview_urls: false,
    ...(s.memory.domain ? { routes: [{ pattern: s.memory.domain, custom_domain: true }] } : {}),
    vars: { PUBLIC_URL: s.memory.url },
    d1_databases: [{ binding: "DB", database_name: s.memory.d1.name, database_id: s.memory.d1.id, migrations_dir: rel(path.join(packageRoot, "server", "migrations")) }],
    kv_namespaces: [{ binding: "OAUTH_KV", id: s.memory.kv.id }],
    // Your skills, served over MCP: reachable only through the SKILLS binding, never as public files.
    assets: { directory: "assets", binding: "SKILLS", run_worker_first: true },
    triggers: { crons: [] },
    observability: { enabled: true },
  };
  writeFileSync(configPath(project), `// Generated by agent-cloud from agent-cloud.json; changes here are overwritten.\n${JSON.stringify(config, null, 2)}\n`);
  return configPath(project);
}

/** Path to Wrangler's own CLI script (run with node, so no shell is needed on Windows). */
export function wranglerBin(): string {
  const require = createRequire(path.join(packageRoot, "package.json"));
  return path.join(path.dirname(require.resolve("wrangler/package.json")), "bin", "wrangler.js");
}

/** Runs Wrangler in the project's build folder. Output is returned unless `inherit` shows it live. */
export function wrangler(project: string, args: string[], opts: { inherit?: boolean; input?: string; config?: boolean } = {}): string {
  const withConfig = opts.config === false ? args : [...args, "--config", configPath(project)];
  const options: ExecFileSyncOptions = {
    cwd: buildDir(project),
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
    windowsHide: true,
    input: opts.input,
    stdio: opts.inherit ? ["inherit", "inherit", "inherit"] : [opts.input === undefined ? "inherit" : "pipe", "pipe", "pipe"],
  };
  mkdirSync(buildDir(project), { recursive: true });
  return String(execFileSync(process.execPath, [wranglerBin(), ...withConfig], options) ?? "");
}
