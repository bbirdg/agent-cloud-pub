/**
 * Where each harness keeps its rules, skills, subagents, hooks and MCP servers, and in what format.
 * Content comes from config/ in the open standards (AGENTS.md-style markdown, Agent Skills, MCP);
 * an adapter only knows paths and formats. Add a harness = add an adapter (or a generic-agents-md entry).
 */
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, realpathSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { type Entry, expandHome, hash, readText, replaceFile, Sync, writeText } from "./core.ts";
import { desktopConfigPath } from "./desktop.ts";
import { type Catalog, defFor, findTomlBlock, toAntigravity, toClaude, toClaudeDesktop, toCodex, toCursor, tomlBlock } from "./mcp.ts";

export interface Content {
  home: string;
  /** Values for the catalog's ${env:NAME} secrets. */
  secrets: Record<string, string | undefined>;
  /** How Claude Code's MCP servers are written: through its CLI (real runs), or straight into <home>/.claude.json (test runs). */
  claudeMcp: "cli" | "file";
  globalRules: string;
  agentRules(harness: string): string;
  memoryBlock: string;
  extraRules: { name: string; text: string }[]; // config/rules/*.md other than global.md
  /** Your own skills (config/skills + agent-memory), plus the mirrored ones for harnesses that share one folder. */
  skills: Skill[];
  /** Installed skills copied to a harness's separate folder (Codex: ~/.codex/skills). */
  mirrored: Skill[];
  agents(harness: string): { file: string; text: string }[];
  catalog: Catalog;
  hookCommand: string;
}

export type Skill = { name: string; dir: string | null; files: Record<string, string> };

/** Where each harness reads skills from (relative to home). Codex also reads its older ~/.codex/skills. */
export const SKILL_DIRS: Record<string, string> = {
  "claude-code": ".claude/skills",
  codex: ".agents/skills",
  antigravity: ".gemini/config/skills",
};
export const CODEX_MIRROR_DIR = ".codex/skills";

const GENERATED = "<!-- Generated by agent-cloud from config/rules. Edit your agent-cloud folder, then run: npx agent-cloud sync --apply -->";

export function rulesFile(c: Content, harness: string, title: string): string {
  const parts = [GENERATED, `# ${title}`, c.globalRules.trim(), c.agentRules(harness).trim(), c.memoryBlock.trim()].filter(Boolean);
  return parts.join("\n\n") + "\n";
}

// ---------- shared entry builders ----------

function fileEntry(id: string, file: string, desired: string | null, adoptable = true): Entry {
  return { id, read: () => readText(file), desired, write: (t) => writeText(file, t), adoptable, backupFile: file };
}

/**
 * One entry per skill folder: owns the whole folder (written from scratch each time it changes).
 * Ids are `<harness>:<kind>:<name>`; kind "mirror-skill" marks installed skills copied to a folder of their own.
 */
function skillEntries(sync: Sync, prefix: string, dir: string, skills: Skill[], kind = "skill"): Entry[] {
  const entries: Entry[] = [];
  const want = new Set<string>();
  for (const skill of skills) {
    const id = `${prefix}:${kind}:${skill.name}`;
    want.add(id);
    const target = path.join(dir, skill.name);
    // Never write through a link, or onto the folder the skill is being copied from.
    if (isLinkOrSame(target, skill.dir)) continue;
    const desired = folderDigest(skill.files);
    entries.push({
      id,
      read: () => (existsSync(target) ? folderDigest(readFolder(target)) : null),
      desired,
      write: (t) => {
        writeFolder(target, t === null ? null : skill.files);
      },
      adoptable: true,
      backupDir: target,
    });
  }
  for (const id of sync.managedIds(`${prefix}:${kind}:`)) {
    if (want.has(id)) continue;
    const target = path.join(dir, id.slice(`${prefix}:${kind}:`.length));
    entries.push({ id, read: () => (existsSync(target) ? folderDigest(readFolder(target)) : null), desired: null, write: () => writeFolder(target, null) });
  }
  return entries;
}

export function readFolder(dir: string): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (d: string, rel: string) => {
    for (const name of readdirSync(d)) {
      const full = path.join(d, name);
      const r = rel ? `${rel}/${name}` : name;
      if (statSync(full).isDirectory()) walk(full, r);
      else out[r] = readFileSync(full).toString("base64");
    }
  };
  walk(dir, "");
  return out;
}

export const folderDigest = (files: Record<string, string>) =>
  Object.keys(files)
    .sort()
    .map((k) => `${k}:${hash(files[k]!)}`)
    .join("\n");

function isLinkOrSame(target: string, source: string | null): boolean {
  if (!existsSync(target)) return false;
  if (lstatSync(target).isSymbolicLink()) return true;
  return source !== null && existsSync(source) && realpathSync(target) === realpathSync(source);
}

/** Replaces a folder with exactly `files` (base64 contents, so binary files stay intact); null removes it. */
export function writeFolder(dir: string, files: Record<string, string> | null): void {
  if (existsSync(dir) && lstatSync(dir).isSymbolicLink()) throw new Error(`Refusing to replace a linked folder: ${dir}`);
  rmSync(dir, { recursive: true, force: true });
  if (!files) return;
  for (const [rel, b64] of Object.entries(files)) {
    const file = path.join(dir, ...rel.split("/"));
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, Buffer.from(b64, "base64"));
  }
}

function agentFileEntries(sync: Sync, prefix: string, dir: string, files: { file: string; text: string }[]): Entry[] {
  const entries: Entry[] = files.map(({ file, text }) => fileEntry(`${prefix}:agent:${file}`, path.join(dir, file), text));
  const want = new Set(entries.map((e) => e.id));
  for (const id of sync.managedIds(`${prefix}:agent:`)) {
    if (!want.has(id)) entries.push(fileEntry(id, path.join(dir, id.slice(`${prefix}:agent:`.length)), null));
  }
  return entries;
}

/** A key inside a JSON object file (e.g. mcpServers.<name>), owned individually. */
function jsonKeyEntry(id: string, file: string, keyPath: string[], desired: unknown | null): Entry {
  const load = () => (existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>) : {});
  const get = (obj: Record<string, unknown>) => keyPath.reduce<unknown>((o, k) => (o && typeof o === "object" ? (o as Record<string, unknown>)[k] : undefined), obj);
  return {
    id,
    read: () => {
      const v = get(load());
      return v === undefined ? null : JSON.stringify(v, null, 2);
    },
    desired: desired === null ? null : JSON.stringify(desired, null, 2),
    write: (t) => {
      const obj = load();
      let cur: Record<string, unknown> = obj;
      for (const k of keyPath.slice(0, -1)) cur = (cur[k] ??= {}) as Record<string, unknown>;
      const last = keyPath.at(-1)!;
      if (t === null) delete cur[last];
      else cur[last] = JSON.parse(t);
      // These files hold MCP servers, whose secrets are filled in: private, and never seen half-written.
      replaceFile(file, JSON.stringify(obj, null, 2) + "\n", { private: true });
    },
    adoptable: true,
    backupFile: file,
  };
}

function mcpRemovals(sync: Sync, prefix: string, want: Set<string>, make: (name: string) => Entry): Entry[] {
  return sync.managedIds(`${prefix}:mcp:`).filter((id) => !want.has(id)).map((id) => make(id.slice(`${prefix}:mcp:`.length)));
}

// ---------- harnesses ----------

export function claudeCode(sync: Sync, c: Content): Entry[] {
  const base = path.join(c.home, ".claude");
  const entries: Entry[] = [fileEntry("claude-code:rules", path.join(base, "CLAUDE.md"), rulesFile(c, "claude-code", "Global instructions (Claude Code)"))];
  for (const r of c.extraRules) entries.push(fileEntry(`claude-code:rule:${r.name}`, path.join(base, "rules", r.name), r.text));
  entries.push(...skillEntries(sync, "claude-code", path.join(c.home, SKILL_DIRS["claude-code"]!), c.skills));
  entries.push(...agentFileEntries(sync, "claude-code", path.join(base, "agents"), c.agents("claude-code")));

  // Settings: our SessionStart hook and local auto-memory off (shared memory replaces it).
  const settings = path.join(base, "settings.json");
  entries.push(jsonKeyEntry("claude-code:setting:autoMemoryEnabled", settings, ["autoMemoryEnabled"], false));
  entries.push(hookEntry(settings, c.hookCommand));

  // MCP servers: user-scope entries in ~/.claude.json, which Claude Code itself keeps writing, so real runs go through
  // its own CLI (the documented way). Secrets stay ${NAME} references (see toClaude), never values on the command line.
  // Test runs (--home) write the file directly: they never call the real `claude`.
  const claudeJson = path.join(c.home, ".claude.json");
  const load = () => (existsSync(claudeJson) ? (JSON.parse(readFileSync(claudeJson, "utf8")) as { mcpServers?: Record<string, unknown> }) : {});
  const want = new Set<string>();
  // Compared canonically (sorted keys, empty values dropped) so only servers that really differ are rewritten.
  const make = (name: string, def: unknown | null): Entry => ({
    id: `claude-code:mcp:${name}`,
    read: () => {
      const v = load().mcpServers?.[name];
      return v === undefined ? null : canonical(v);
    },
    desired: def === null ? null : canonical(def),
    write: (t) => {
      if (c.claudeMcp === "file") {
        const all = load();
        all.mcpServers ??= {};
        if (t === null) delete all.mcpServers[name];
        else all.mcpServers[name] = JSON.parse(t);
        replaceFile(claudeJson, JSON.stringify(all, null, 2) + "\n");
        return;
      }
      const previous = load().mcpServers?.[name];
      const run = (args: string[]) => {
        try {
          execFileSync("claude", args, { stdio: "ignore", windowsHide: true });
        } catch (e) {
          if ((e as NodeJS.ErrnoException).code === "ENOENT") throw new Error("the `claude` command wasn't found on PATH (Claude Code's native installer adds it)");
          throw new Error(`\`claude mcp ${args[1]}\` failed`); // never the command line: it holds the server's definition
        }
      };
      if (previous !== undefined) run(["mcp", "remove", "--scope", "user", name]);
      if (t === null) return;
      try {
        run(["mcp", "add-json", "--scope", "user", name, t]);
      } catch (error) {
        // Put the previous definition back rather than leave the server missing.
        if (previous !== undefined) run(["mcp", "add-json", "--scope", "user", name, JSON.stringify(previous)]);
        throw error;
      }
    },
    adoptable: true,
  });
  for (const [name, entry] of Object.entries(c.catalog.servers)) {
    const def = defFor(entry, "claude-code");
    if (!def) continue;
    want.add(`claude-code:mcp:${name}`);
    entries.push(make(name, toClaude(def)));
  }
  entries.push(...mcpRemovals(sync, "claude-code", want, (n) => make(n, null)));
  return entries;
}

/** Stable JSON: keys sorted, empty arrays/objects and empty strings dropped. */
export function canonical(value: unknown): string {
  const clean = (v: unknown): unknown => {
    if (Array.isArray(v)) return v.map(clean);
    if (v && typeof v === "object") {
      const out: Record<string, unknown> = {};
      for (const k of Object.keys(v).sort()) {
        const x = clean((v as Record<string, unknown>)[k]);
        if (x === "" || x === undefined || (Array.isArray(x) && x.length === 0) || (x && typeof x === "object" && !Array.isArray(x) && Object.keys(x).length === 0)) continue;
        out[k] = x;
      }
      return out;
    }
    return v;
  };
  return JSON.stringify(clean(value));
}

function hookEntry(settingsFile: string, command: string): Entry {
  const load = () => (existsSync(settingsFile) ? (JSON.parse(readFileSync(settingsFile, "utf8")) as Record<string, any>) : {});
  // Ours whichever project folder it points to: this package's installed CLI (`.../node_modules/agent-cloud/dist/src/cli.js"
  // hook`), exactly this run's command, or the hook-context.mjs of versions before the package. Nothing else.
  const mine = /hook-context\.mjs"?\s*$|[\\/]node_modules[\\/]agent-cloud[\\/]dist[\\/]src[\\/]cli\.js"?\s+hook\s*$/;
  const ours = (g: any) => (g?.hooks ?? []).some((h: any) => typeof h.command === "string" && (h.command === command || mine.test(h.command)));
  return {
    id: "claude-code:hook:session-start",
    read: () => {
      const group = (load().hooks?.SessionStart ?? []).find(ours);
      return group ? JSON.stringify(group, null, 2) : null;
    },
    desired: JSON.stringify({ hooks: [{ type: "command", command, timeout: 10 }] }, null, 2),
    write: (t) => {
      const s = load();
      s.hooks ??= {};
      const others = (s.hooks.SessionStart ?? []).filter((g: any) => !ours(g));
      s.hooks.SessionStart = t === null ? others : [...others, JSON.parse(t)];
      if (s.hooks.SessionStart.length === 0) delete s.hooks.SessionStart;
      if (Object.keys(s.hooks).length === 0) delete s.hooks;
      writeText(settingsFile, JSON.stringify(s, null, 2) + "\n");
    },
    adoptable: true,
    backupFile: settingsFile,
  };
}

export function codex(sync: Sync, c: Content): Entry[] {
  const base = path.join(c.home, ".codex");
  const entries: Entry[] = [fileEntry("codex:rules", path.join(base, "AGENTS.md"), rulesFile(c, "codex", "Global instructions (Codex)"))];
  entries.push(...skillEntries(sync, "codex", path.join(c.home, SKILL_DIRS.codex!), c.skills));
  // Installed skills go to Codex's older folder, which Cursor doesn't read (~/.agents/skills would show them twice there).
  entries.push(...skillEntries(sync, "codex", path.join(c.home, CODEX_MIRROR_DIR), c.mirrored, "mirror-skill"));
  entries.push(...agentFileEntries(sync, "codex", path.join(base, "agents"), c.agents("codex")));

  const config = path.join(base, "config.toml");
  const want = new Set<string>();
  const make = (name: string, table: Record<string, unknown> | null): Entry => ({
    id: `codex:mcp:${name}`,
    read: () => {
      const text = readText(config);
      const block = text && findTomlBlock(text, name);
      return block ? text!.slice(block.start, block.end).trimEnd() + "\n" : null;
    },
    desired: table === null ? null : tomlBlock(name, table),
    write: (t) => {
      const text = readText(config) ?? "";
      const block = findTomlBlock(text, name);
      let next: string;
      if (block) next = text.slice(0, block.start) + (t ?? "") + text.slice(block.end).replace(/^\n+/, t ? "\n" : "");
      else next = t ? text.trimEnd() + "\n\n" + t : text;
      writeText(config, next.replace(/\n{3,}/g, "\n\n"), { private: true });
    },
    adoptable: true,
    backupFile: config,
  });
  for (const [name, entry] of Object.entries(c.catalog.servers)) {
    const def = defFor(entry, "codex");
    if (!def) continue;
    want.add(`codex:mcp:${name}`);
    entries.push(make(name, toCodex(def, c.secrets)));
  }
  entries.push(...mcpRemovals(sync, "codex", want, (n) => make(n, null)));
  return entries;
}

export function antigravity(sync: Sync, c: Content): Entry[] {
  const base = path.join(c.home, ".gemini");
  const entries: Entry[] = [fileEntry("antigravity:rules", path.join(base, "AGENTS.md"), rulesFile(c, "antigravity", "Global instructions (Antigravity)"))];
  // Path-scoped rules: Antigravity wants trigger/globs frontmatter instead of Claude's paths list.
  for (const r of c.extraRules) entries.push(fileEntry(`antigravity:rule:${r.name}`, path.join(base, "config", "rules", r.name), toAntigravityRule(r.text)));
  entries.push(...skillEntries(sync, "antigravity", path.join(c.home, SKILL_DIRS.antigravity!), c.skills));
  entries.push(...agentFileEntries(sync, "antigravity", path.join(base, "config", "plugins", "agent-cloud", "agents"), c.agents("antigravity")));
  entries.push(
    fileEntry(
      "antigravity:plugin",
      path.join(base, "config", "plugins", "agent-cloud", "plugin.json"),
      JSON.stringify({ name: "agent-cloud", displayName: "agent-cloud", version: "1.0.0", description: "Subagents managed by the agent-cloud repo." }, null, 2) + "\n",
    ),
  );

  const config = path.join(base, "config", "mcp_config.json");
  const want = new Set<string>();
  for (const [name, entry] of Object.entries(c.catalog.servers)) {
    const def = defFor(entry, "antigravity");
    if (!def) continue;
    want.add(`antigravity:mcp:${name}`);
    entries.push(jsonKeyEntry(`antigravity:mcp:${name}`, config, ["mcpServers", name], toAntigravity(def, c.secrets)));
  }
  entries.push(...mcpRemovals(sync, "antigravity", want, (n) => jsonKeyEntry(`antigravity:mcp:${n}`, config, ["mcpServers", n], null)));
  return entries;
}

export function toAntigravityRule(text: string): string {
  const m = /^---\n([\s\S]*?)\n---\n?/.exec(text.replace(/\r\n/g, "\n"));
  if (!m) return `---\ntrigger: always_on\n---\n\n${text}`;
  const globs = [...m[1]!.matchAll(/^\s*-\s*["']?([^"'\n]+)["']?\s*$/gm)].map((g) => g[1]!.trim());
  const expanded = globs.flatMap((g) => {
    const brace = /^(.*)\{([^}]+)\}(.*)$/.exec(g);
    return brace ? brace[2]!.split(",").map((x) => `${brace[1]}${x.trim()}${brace[3]}`) : [g];
  });
  const body = text.replace(/\r\n/g, "\n").slice(m[0].length);
  return `---\ntrigger: glob\nglobs: "${expanded.join(", ")}"\n---\n${body}`;
}

export function cursor(sync: Sync, c: Content): Entry[] {
  // Cursor reads ~/.claude/skills itself, so skills are not copied again. User Rules aren't a file:
  // the CLI prints the rules text to paste into Settings > Rules > User Rules when it changes.
  const config = path.join(c.home, ".cursor", "mcp.json");
  const entries: Entry[] = [];
  const want = new Set<string>();
  for (const [name, entry] of Object.entries(c.catalog.servers)) {
    const def = defFor(entry, "cursor");
    if (!def) continue;
    want.add(`cursor:mcp:${name}`);
    entries.push(jsonKeyEntry(`cursor:mcp:${name}`, config, ["mcpServers", name], toCursor(def, c.secrets)));
  }
  entries.push(...mcpRemovals(sync, "cursor", want, (n) => jsonKeyEntry(`cursor:mcp:${n}`, config, ["mcpServers", n], null)));
  return entries;
}

/**
 * The Claude desktop app: only its MCP servers (its chat has no rules file or skills folder; its Code tab is Claude
 * Code). Every server it loads is started for every chat, so it gets only the servers listed for it in
 * harnesses.json, defined as its catalog entry's "claude-desktop", "default" or "claude-code" definition.
 */
export function claudeDesktop(sync: Sync, c: Content, servers: string[], warn: (m: string) => void): Entry[] {
  const config = desktopConfigPath(c.home);
  const entries: Entry[] = [];
  const want = new Set<string>();
  for (const name of servers) {
    const entry = c.catalog.servers[name];
    if (!entry) {
      warn(`claude-desktop: ${name} is listed in harnesses.json but not in config/mcp/catalog.json`);
      continue;
    }
    const def = entry["claude-desktop"] === false ? null : defFor(entry, "claude-desktop") ?? defFor(entry, "claude-code");
    if (!def) continue;
    want.add(`claude-desktop:mcp:${name}`);
    entries.push(jsonKeyEntry(`claude-desktop:mcp:${name}`, config, ["mcpServers", name], toClaudeDesktop(name, def, c.secrets)));
  }
  entries.push(...mcpRemovals(sync, "claude-desktop", want, (n) => jsonKeyEntry(`claude-desktop:mcp:${n}`, config, ["mcpServers", n], null)));
  return entries;
}

/** Any harness that reads an AGENTS.md-style rules file and an Agent Skills folder. */
export function genericAgentsMd(sync: Sync, c: Content, name: string, opts: { rulesFile: string; skillsDir?: string }): Entry[] {
  const entries: Entry[] = [fileEntry(`${name}:rules`, expandHome(opts.rulesFile, c.home), rulesFile(c, name, `Global instructions (${name})`))];
  if (opts.skillsDir) entries.push(...skillEntries(sync, name, expandHome(opts.skillsDir, c.home), c.skills));
  return entries;
}
